import type Parser from "./Parser";
import type { AnyParseNode, NodeType, ParseNode } from "./parseNode";
import type Style from "./Style";
import type { Token } from "./Token";
import type { MathDomNode } from "./tree";
import type { ArgType } from "./types";

/** The context passed to a function handler. See Parser#callFunction. */
export interface FunctionContext {
  funcName: string;
  parser: Parser;
  token?: Token | null;
  breakOnTokenText?: string | null;
}

/**
 * A function handler receives the parsed arguments and returns a parse node.
 * Most handlers return a node of their own `type`, but some return another
 * node instead, e.g. an "ordgroup" or the unchanged base of \sideset.
 */
export type FunctionHandler = (
  context: FunctionContext,
  args: AnyParseNode[],
  optArgs: Array<AnyParseNode | null | undefined>
) => AnyParseNode;

/** Builds the MathML of a parse node of the given type. */
export type MathMLBuilder<NODETYPE extends NodeType> = (
  group: ParseNode<NODETYPE>,
  style: Style
) => MathDomNode;

export interface FunctionPropSpec {
  // The number of arguments the function takes.
  numArgs: number;

  // An array corresponding to each argument of the function, giving the
  // type of argument that should be parsed. Its length should be equal
  // to `numOptionalArgs + numArgs`, and types for optional arguments
  // should appear before types for mandatory arguments.
  argTypes?: ArgType[];

  // Whether it expands to a single token or a braced group of tokens.
  // If it's grouped, it can be used as an argument to primitive commands,
  // such as \sqrt (without the optional argument) and super/subscript.
  allowedInArgument?: boolean;

  // Whether or not the function is allowed inside text mode
  // (default false)
  allowedInText?: boolean;

  // Whether or not the function is allowed inside text mode
  // (default true)
  allowedInMath?: boolean;

  // (optional) The number of optional arguments the function
  // should parse. If the optional arguments aren't found,
  // `null` will be passed to the handler in their place.
  // (default 0)
  numOptionalArgs?: number;

  // Must be true if the function is an infix operator.
  infix?: boolean;

  // Whether or not the function is a TeX primitive.
  primitive?: boolean;
}

export interface FunctionSpec<NODETYPE extends NodeType> {
  // Unique string to differentiate parse nodes.
  type: NODETYPE;

  // The first argument to defineFunction is a single name or a list of names.
  // All functions named in such a list will share a single implementation.
  names: string[];

  // Properties that control how the functions are parsed.
  props: FunctionPropSpec;

  // The handler is called to handle these functions and their arguments and
  // returns a `ParseNode`.
  handler: FunctionHandler;

  // This function returns an object representing the MathML structure.
  // This should be omitted if the type does not appear in the parse tree
  // (e.g. when the handler returns an "ordgroup").
  mathmlBuilder?: MathMLBuilder<NODETYPE>;
}

/**
 * Final function spec for use at parse time.
 * This is almost identical to `FunctionPropSpec`, except it
 * 1. includes the function handler, and
 * 2. requires all arguments except argTypes.
 * It is generated by `defineFunction()` below.
 */
export interface FunctionSpecData {
  type: NodeType;
  numArgs: number;
  argTypes?: ArgType[];
  allowedInArgument: boolean;
  allowedInText: boolean;
  allowedInMath: boolean;
  numOptionalArgs: number;
  infix: boolean;
  primitive: boolean;
  handler: FunctionHandler;
}

/** A MathML builder that accepts any parse node. Used by the registry. */
type AnyMathMLBuilder = (group: AnyParseNode, style: Style) => MathDomNode;

/**
 * All registered functions.
 * `functions.js` just exports this same dictionary again and makes it public.
 * `Parser.js` requires this dictionary.
 */
export const _functions: Record<string, FunctionSpecData> = {}

/**
 * All MathML builders. Should be only used in the `define*` and the `build*ML`
 * functions.
 */
export const _mathmlGroupBuilders: Partial<Record<NodeType, AnyMathMLBuilder>> = {}

/**
 * Register a MathML builder. Each builder only ever receives nodes of its own
 * type (see buildMathML.js), so it is safe to store it as `AnyMathMLBuilder`.
 */
export const registerMathMLBuilder = <NODETYPE extends NodeType>(
  type: NODETYPE,
  mathmlBuilder: MathMLBuilder<NODETYPE>
): void => {
  _mathmlGroupBuilders[type] = mathmlBuilder as unknown as AnyMathMLBuilder
}

const defineFunction = <NODETYPE extends NodeType>({
  type,
  names,
  props,
  handler,
  mathmlBuilder
}: FunctionSpec<NODETYPE>): void => {
  // Set default values of functions
  const data: FunctionSpecData = {
    type,
    numArgs: props.numArgs,
    argTypes: props.argTypes,
    allowedInArgument: !!props.allowedInArgument,
    allowedInText: !!props.allowedInText,
    allowedInMath: props.allowedInMath ?? true,
    numOptionalArgs: props.numOptionalArgs ?? 0,
    infix: !!props.infix,
    primitive: !!props.primitive,
    handler
  }
  for (let i = 0; i < names.length; ++i) {
    _functions[names[i]] = data
  }
  if (mathmlBuilder) {
    registerMathMLBuilder(type, mathmlBuilder)
  }
}

export default defineFunction

/**
 * Use this to register only the MathML builder for a function(e.g.
 * if the function's ParseNode is generated in Parser.js rather than via a
 * stand-alone handler provided to `defineFunction`).
 */
export const defineFunctionBuilders = <NODETYPE extends NodeType>({
  type,
  mathmlBuilder
}: {
  type: NODETYPE;
  mathmlBuilder?: MathMLBuilder<NODETYPE>;
}): void => {
  defineFunction({
    type,
    names: [],
    props: { numArgs: 0 },
    handler() {
      throw new Error("Should never be called.")
    },
    mathmlBuilder
  })
}

export const normalizeArgument = (arg: AnyParseNode): AnyParseNode => {
  return arg.type === "ordgroup" && arg.body.length === 1 ? arg.body[0] : arg
}

// Since the corresponding buildMathML function expects a
// list of elements, we normalize for different kinds of arguments
export const ordargument = (arg: AnyParseNode): AnyParseNode[] => {
  return arg.type === "ordgroup" ? arg.body : [arg]
}
