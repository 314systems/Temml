import { registerMathMLBuilder } from "./defineFunction";
import type { MathMLBuilder } from "./defineFunction";
import type Parser from "./Parser";
import type { AnyParseNode, NodeType } from "./parseNode";
import type { Mode } from "./types";

/**
 * The context passed to an environment handler. See functions/environment.js.
 */
export interface EnvContext {
  mode: Mode;
  envName: string;
  parser: Parser;
  // Set when the environment is called from \bordermatrix and friends.
  delimiters?: string[];
}

/**
 * - context: information and references provided by the parser
 * - args: an array of arguments passed to \begin{name}
 * - optArgs: an array of optional arguments passed to \begin{name}
 */
export type EnvHandler = (
  context: EnvContext,
  args: AnyParseNode[],
  optArgs: Array<AnyParseNode | null | undefined>
) => AnyParseNode;

/**
 *  - numArgs: (default 0) The number of arguments after the \begin{name} function.
 */
export interface EnvProps {
  numArgs?: number;
}

export interface EnvSpec<NODETYPE extends NodeType> {
  type: NODETYPE;
  names: string[];
  props: EnvProps;
  handler: EnvHandler;
  mathmlBuilder?: MathMLBuilder<NODETYPE>;
}

/**
 * Final environment spec for use at parse time.
 * This is almost identical to `EnvSpec`, except it
 * 1. includes the function handler
 * 2. requires all arguments except argType
 * It is generated by `defineEnvironment()` below.
 */
export interface EnvSpecData {
  type: NodeType;
  numArgs: number;
  allowedInText: boolean;
  numOptionalArgs: number;
  handler: EnvHandler;
}

/**
 * All registered environments.
 * `environments.js` exports this same dictionary again and makes it public.
 * `Parser.js` requires this dictionary via `environments.js`.
 */
export const _environments: Record<string, EnvSpecData> = {};

export default function defineEnvironment<NODETYPE extends NodeType>({
  type,
  names,
  props,
  handler,
  mathmlBuilder
}: EnvSpec<NODETYPE>): void {
  // Set default values of environments.
  const data: EnvSpecData = {
    type,
    numArgs: props.numArgs ?? 0,
    allowedInText: false,
    numOptionalArgs: 0,
    handler
  };
  for (let i = 0; i < names.length; ++i) {
    _environments[names[i]] = data;
  }
  if (mathmlBuilder) {
    registerMathMLBuilder(type, mathmlBuilder);
  }
}
